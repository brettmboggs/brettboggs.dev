import Foundation

/// One way to make or replace an ingredient that is not in the kitchen.
///
/// `options` is a list of groups; one item from every group is needed. So
/// buttermilk is `[["milk"], ["lemon juice", "white vinegar"]]`: milk, and
/// either acid.
struct Substitution: Hashable {
    let target: String
    let options: [[String]]
    let note: String
    /// A homemade version of the thing rather than a swap for it.
    let isHomemade: Bool

    init(_ target: String, _ options: [[String]], _ note: String, homemade: Bool = false) {
        self.target = target
        self.options = options
        self.note = note
        self.isHomemade = homemade
    }

    /// The ingredients this substitution actually uses, given the pantry.
    func uses(in index: PantryIndex) -> [String] {
        options.compactMap { group in group.first { index.has($0) } }
    }
}

