    /// Every rule for a target, in the order written, which is the order of
    /// preference.
    static let byTarget: [String: [Substitution]] = {
        var map: [String: [Substitution]] = [:]
        for rule in all { map[rule.target, default: []].append(rule) }
        return map
    }()

    /// The best substitution the pantry can actually make for `key`.
    static func available(for key: String, in index: PantryIndex) -> Substitution? {
        guard let rules = byTarget[key] else { return nil }
        return rules.first { rule in
            rule.options.allSatisfy { group in group.contains { index.has($0) } }
        }
    }

    /// Everything the catalogue knows about making do without `key`.
    static func ideas(for key: String) -> [Substitution] {
        byTarget[key] ?? []
    }
